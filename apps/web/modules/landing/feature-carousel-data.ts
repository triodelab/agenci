/** Resize remaining remote photos at their source; local originals use Next Image. */
export function featureImageLoader({
  src,
  width,
  quality = 88,
}: {
  src: string;
  width: number;
  quality?: number;
}) {
  // Local originals use Next's built-in optimizer instead of provider resizing.
  if (src.startsWith("/")) return src;
  const url = new URL(src);
  const original = featureCards.find((card) => card.image === src);
  url.searchParams.delete("h");
  url.searchParams.delete("dpr");
  url.searchParams.set(
    "w",
    String(Math.min(width, original?.sourceSize.width ?? width)),
  );
  url.searchParams.set("q", String(quality));
  url.searchParams.set("auto", "format,compress");
  url.searchParams.set("fit", "max");
  return url.toString();
}

export function wrapFeatureIndex(index: number, count: number) {
  return ((index % count) + count) % count;
}

/** The native track has one visual clone at either end for seamless wrapping. */
export function normalizeFeaturePosition(position: number, count: number) {
  if (position < 0.5) return position + count;
  if (position > count + 0.5) return position - count;
  return position;
}
